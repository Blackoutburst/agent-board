/* Synthetic localhost-only Firefox acceptance test. Requires Playwright. */
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { firefox } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.BOARD_TEST_URL || 'http://127.0.0.1:18765';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname)) throw new Error('Synthetic browser test only supports loopback');

(async () => {
  const browser = await firefox.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const theme = path.join(__dirname, '../qa/platform-theme.css');
  await page.route('**/platform/theme.css', route => route.fulfill({ contentType: 'text/css', body: fs.existsSync(theme) ? fs.readFileSync(theme, 'utf8') : '' }));
  try {
    await page.goto(origin);
    await page.getByLabel('File Browser username').fill('TheScreamer');
    await page.getByLabel('Password', { exact: true }).fill('local-ui-fixture-only');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('button', { name: 'Projets', exact: true }).click();
    await page.getByRole('button', { name: 'Créer un projet', exact: true }).click();
    let dialog = page.getByRole('dialog');
    const projectName = `Plateforme — test Firefox ${Date.now()}`;
    await dialog.getByLabel('Nom du projet', { exact: true }).fill(projectName);
    await dialog.getByLabel('Description', { exact: true }).fill('Projet synthétique de validation des parcours.');
    await dialog.getByLabel('Contexte partagé', { exact: false }).fill('Objectif : vérifier les projets et tickets.\nDécision : aucune donnée réelle dans ce test.');
    await dialog.getByLabel('Dépôt HTTPS', { exact: true }).fill('https://example.test/project');
    await dialog.getByLabel('Environnement', { exact: true }).fill('Serveur local, deux comptes fictifs.');
    await dialog.getByRole('button', { name: 'Créer le projet', exact: true }).click();
    await page.getByRole('heading', { name: projectName, exact: true }).waitFor();
    const projectId = new URL(page.url()).searchParams.get('project');
    assert.ok(projectId);
    await page.getByRole('button', { name: 'Créer un ticket', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Titre du ticket', { exact: true }).fill('Vérifier la connexion Google');
    await dialog.getByLabel('Description', { exact: true }).fill('Texte inoffensif : <img src=x onerror=alert(1)> doit rester du texte.');
    await dialog.getByLabel('Critères de validation', { exact: true }).fill('Un responsable unique et des preuves conservées.');
    await dialog.getByLabel('Priorité', { exact: true }).selectOption('high');
    await dialog.getByLabel('Responsable', { exact: true }).selectOption('thescreamer');
    await dialog.getByRole('button', { name: 'Créer le ticket', exact: true }).click();
    await page.getByRole('heading', { name: 'Vérifier la connexion Google', exact: false }).waitFor();
    const ticketId = new URL(page.url()).searchParams.get('ticket');
    assert.ok(ticketId);
    assert.equal(await page.locator('.ticket-view img').count(), 0);
    await page.screenshot({ path: path.join(__dirname, '../qa/ticket-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Prendre en charge', exact: true }).click();
    await page.getByText('En cours', { exact: true }).first().waitFor();
    await page.getByRole('button', { name: 'Modifier', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Statut', { exact: true }).selectOption('done');
    await dialog.getByLabel('Résultat', { exact: true }).fill('Parcours Firefox validé.');
    await dialog.getByLabel('Preuves de validation', { exact: true }).fill('Création, attribution, prise en charge et affichage testés sur données fictives.');
    await dialog.getByRole('button', { name: 'Enregistrer le ticket', exact: true }).click();
    await page.getByText('Terminé', { exact: true }).first().waitFor();
    const ticket = await (await page.request.get(`${origin}/api/tickets/${ticketId}`)).json();
    assert.equal(ticket.ticket.status, 'done');
    assert.equal(ticket.ticket.number, 1);
    const discussion = page.getByRole('link', { name: /discussion/i });
    await discussion.first().click();
    await page.locator('#compose').waitFor();
    const compose = page.locator('#compose');
    await compose.locator('textarea').fill('Validation synthétique de la discussion du ticket.');
    await compose.getByRole('button', { name: /Send/ }).click();
    await page.getByText('Validation synthétique de la discussion du ticket.', { exact: true }).waitFor();
    await page.goto(`${origin}/?project=${projectId}`);
    await page.getByRole('heading', { name: projectName, exact: true }).waitFor();
    await page.screenshot({ path: path.join(__dirname, '../qa/project-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Modifier le projet', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Description', { exact: true }).fill('Brouillon local à préserver.');
    const me = await (await page.request.get(`${origin}/api/me`)).json();
    const project = await (await page.request.get(`${origin}/api/projects/${projectId}`)).json();
    const conflict = await page.request.patch(`${origin}/api/projects/${projectId}`, { headers: { 'X-CSRF-Token': me.csrf_token, Origin: origin }, data: { expected_version: project.version, context: 'Modification concurrente conservée.' } });
    assert.equal(conflict.status(), 200);
    await dialog.getByRole('button', { name: 'Enregistrer le projet', exact: true }).click();
    await dialog.getByRole('button', { name: 'Comparer avec la version actuelle', exact: true }).click();
    await dialog.getByRole('button', { name: 'Réexaminer mon brouillon sur cette version', exact: true }).waitFor();
    assert.equal(await dialog.getByLabel('Description', { exact: true }).inputValue(), 'Brouillon local à préserver.');
    await dialog.getByRole('button', { name: 'Réexaminer mon brouillon sur cette version', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: 'Enregistrer le projet', exact: true }).click();
    await page.getByRole('heading', { name: projectName, exact: true }).waitFor();
    const merged = await (await page.request.get(`${origin}/api/projects/${projectId}`)).json();
    assert.equal(merged.context, 'Modification concurrente conservée.');
    assert.equal(merged.description, 'Brouillon local à préserver.');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${origin}/?ticket=${ticketId}`);
    await page.getByRole('heading', { name: 'Vérifier la connexion Google', exact: false }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
    await page.screenshot({ path: path.join(__dirname, '../qa/ticket-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ firefox: 'passed', projectId, ticketId, flows: ['create_project', 'create_ticket', 'claim', 'complete_with_evidence', 'discussion', 'conflict_preserves_draft', 'mobile'], pageErrors: errors }));
  } catch (error) {
    await page.screenshot({ path: path.join(__dirname, '../qa/failure.png'), fullPage: true });
    console.error(error);
    process.exitCode = 1;
  } finally {
    await browser.close();
  }
})();
