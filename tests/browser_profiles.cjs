    await dialog().waitFor({ state: 'hidden' });
    assert.equal((await api(`/tickets/${assigned.id}`)).ticket.assignee_agent_id, created.id);
    let paused = await api(`/agent-profiles/${created.id}`);
    await api(`/agent-profiles/${created.id}`, { expected_version: paused.version, project_ids: [] }, 'PATCH');
    await page.getByRole('button', { name: 'Edit task', exact: true }).click();
    assert.equal(await dialog().getByLabel('Assigned to', { exact: true }).inputValue(), `agent:${created.id}`);
    assert.match(await dialog().getByLabel('Assigned to', { exact: true }).locator('option:checked').innerText(), /not currently available/);
    await dialog().getByLabel('Description', { exact: true }).fill('Edit preserves an assignment outside the current profile scope.');
